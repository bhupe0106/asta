"""Deterministic local demo composer.

This is deliberately **not** a language model and never claims to be one. It
exists so ASTA remains explorable on a machine without Ollama running. Every
response is prefixed with a clear disclosure and marked ``mode: "demo"`` in the
API metadata. Production deployments can disable it with
``ASTA_ALLOW_DEMO_PROVIDER=false``.
"""
from __future__ import annotations

import asyncio
import re
from collections.abc import AsyncIterator

from app.ai.providers.base import (
    ChatMessage,
    GenerationResult,
    ModelProvider,
    ProviderHealth,
    TokenUsage,
)

DISCLOSURE = (
    "**Local demo mode** — no language model is connected, so this is a structured "
    "starting point generated by ASTA's deterministic composer, not model reasoning. "
    "Start Ollama and select a model in Settings for full intelligence.\n"
)

INTENT_PATTERNS: list[tuple[str, str, list[str]]] = [
    (r"\b(research|source|cite|citation|evidence|study shows|latest|news)\b", "research", [
        "Define the exact question and the decision it informs.",
        "List what you already know and what must be verified.",
        "Collect at least two independent sources per important claim.",
        "Record publication dates so freshness is visible.",
        "Separate verified facts from interpretation in the final write-up.",
    ]),
    (r"\b(learn|teach|explain|study|exam|quiz|homework|math|physics|chemistry|biology)\b", "learn", [
        "Name the concept in one sentence in your own words.",
        "Break it into prerequisites and check each one.",
        "Work one fully solved example, then one unsolved example.",
        "Explain the method aloud as if teaching someone else.",
        "Schedule a short recall session in 1 day, 3 days and 7 days.",
    ]),
    (r"\b(code|bug|error|debug|function|api|sql|react|python|javascript|typescript)\b", "code", [
        "Reproduce the issue with the smallest possible input.",
        "State the expected behaviour and the actual behaviour precisely.",
        "Inspect inputs, outputs and boundaries before changing logic.",
        "Write a failing test that captures the bug.",
        "Apply the smallest fix, then re-run the full test suite.",
    ]),
    (r"\b(data|csv|spreadsheet|excel|analyse|analyze|statistics|trend|chart|report)\b", "data", [
        "Confirm column meanings, units and missing values first.",
        "Check row counts and duplicates before any aggregation.",
        "Describe distributions before testing hypotheses.",
        "Report uncertainty alongside every headline number.",
        "Keep an explicit list of assumptions in the final report.",
    ]),
    (r"\b(write|story|poem|content|caption|brand|marketing|presentation|design)\b", "create", [
        "Define the audience and the single action you want them to take.",
        "Choose one tone and one concrete image or detail to anchor the piece.",
        "Draft without editing; separate creation from judgement.",
        "Cut anything that does not serve the audience.",
        "Read the final version aloud to catch rhythm problems.",
    ]),
    (r"\b(plan|task|project|schedule|roadmap|organise|organize|steps)\b", "plan", [
        "Write the outcome as a measurable finish line.",
        "List every dependency before estimating effort.",
        "Sequence work so each step produces something checkable.",
        "Identify the riskiest assumption and test it first.",
        "Reserve time for review, not only for building.",
    ]),
]

FOLLOW_UPS = {
    "research": "Add a source URL and I will record it as a citation candidate.",
    "learn": "Tell me your level and I will adapt the depth of the explanation.",
    "code": "Paste the error text and the relevant snippet for a focused review.",
    "data": "Attach a CSV and I will compute real descriptive statistics locally.",
    "create": "Share the audience, tone and length you want to aim for.",
    "plan": "Tell me the deadline and constraints and I will structure the steps.",
    "general": "Ask a follow-up or connect a model for full reasoning.",
}


def classify(text: str) -> str:
    lowered = text.lower()
    for pattern, label, _ in INTENT_PATTERNS:
        if re.search(pattern, lowered):
            return label
    return "general"


def _extract_brief(messages: list[ChatMessage]) -> str:
    for msg in messages:
        if msg.role == "system":
            if "[SPECIALIST BRIEF]" in msg.content:
                return msg.content.split("[SPECIALIST BRIEF]", 1)[1].strip()
            marker = '<untrusted source="specialists">'
            if marker in msg.content:
                return msg.content.split(marker, 1)[1].split("</untrusted>", 1)[0].strip()
    return ""


def compose_demo_response(messages: list[ChatMessage]) -> str:
    user_text = next((m.content for m in reversed(messages) if m.role == "user"), "")
    kind = classify(user_text)
    checklist = next((steps for pattern, label, steps in INTENT_PATTERNS if label == kind), None)
    brief = _extract_brief(messages)

    lines = [DISCLOSURE, "### What I can do right now", ""]
    if brief:
        lines += ["**Specialist findings**", "", brief, ""]

    if checklist:
        lines.append(f"### A practical {kind} scaffold")
        lines.append("")
        lines += [f"{i}. {step}" for i, step in enumerate(checklist, 1)]
        lines.append("")
    else:
        lines += [
            "I can organise your request, route it to a specialist, run local data "
            "analysis, search your knowledge base and store approved memories.",
            "",
        ]

    lines += [
        "### Next step",
        "",
        FOLLOW_UPS.get(kind, FOLLOW_UPS["general"]),
        "",
        "> Demo responses never contain invented facts or citations. "
        "For genuine reasoning, run `ollama serve` and pull a model.",
    ]
    return "\n".join(lines)


class DemoProvider(ModelProvider):
    key = "demo"
    display_name = "Local demo composer (non-LLM)"
    kind = "local"

    async def generate(
        self,
        messages: list[ChatMessage],
        *,
        temperature: float = 0.7,
        max_tokens: int = 2048,
        model: str | None = None,
    ) -> GenerationResult:
        text = compose_demo_response(messages)
        return GenerationResult(
            text=text,
            model="asta-demo-composer",
            provider=self.key,
            usage=TokenUsage(len(text) // 4, len(text) // 4),
            latency_ms=20,
        )

    async def generate_stream(
        self,
        messages: list[ChatMessage],
        *,
        temperature: float = 0.7,
        max_tokens: int = 2048,
        model: str | None = None,
    ) -> AsyncIterator[str]:
        text = compose_demo_response(messages)
        # Stream in small word groups so the UI path is identical to a real model.
        for match in re.finditer(r"\S+\s*", text):
            yield match.group(0)
            await asyncio.sleep(0.004)

    async def list_models(self) -> list[str]:
        return ["asta-demo-composer"]

    async def health_check(self) -> ProviderHealth:
        return ProviderHealth(True, "Deterministic demo composer available (no model required).", ["asta-demo-composer"])
